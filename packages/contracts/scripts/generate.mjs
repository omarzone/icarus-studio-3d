import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "..", "..", "..");
export const GENERATED = join(here, "..", "src", "generated.ts");
const BANNER = "// Generated by pnpm gen:contracts. Do not edit.";

// json-schema-to-typescript reads tuples in the draft-07 form; Pydantic writes draft 2020 `prefixItems`.
function draft07Tuples(node) {
  if (Array.isArray(node)) {
    node.forEach(draft07Tuples);
  } else if (node && typeof node === "object") {
    if (Array.isArray(node.prefixItems)) {
      node.items = node.prefixItems;
      delete node.prefixItems;
    }
    Object.values(node).forEach(draft07Tuples);
  }
  return node;
}

// Field titles would become type names ("revision" → `Revision`) and collide with models; only models keep names.
function dropFieldTitles(schema) {
  const strip = (node, isModel) => {
    if (Array.isArray(node)) {
      node.forEach((item) => strip(item, false));
    } else if (node && typeof node === "object") {
      if (!isModel) {
        delete node.title;
      }
      for (const [key, value] of Object.entries(node)) {
        if (key === "$defs" && value && typeof value === "object") {
          Object.values(value).forEach((model) => strip(model, true));
        } else {
          strip(value, false);
        }
      }
    }
  };
  strip(schema, true);
  return schema;
}

export async function generate() {
  const schemaPath = join(mkdtempSync(join(tmpdir(), "icarus-contracts-")), "schema.json");
  execFileSync(
    "uv",
    ["run", "--project", join(repo, "services", "engine"), "python", "-m", "icarus.contracts.export", schemaPath],
    {
      stdio: "inherit",
    },
  );
  const schema = dropFieldTitles(draft07Tuples(JSON.parse(readFileSync(schemaPath, "utf8"))));
  const ts = await compile(schema, "IcarusContracts", {
    bannerComment: BANNER,
    unreachableDefinitions: true,
    additionalProperties: false,
    declareExternallyReferenced: true,
    style: { semi: true, singleQuote: false },
  });
  return ts.replace(/export interface IcarusContracts \{[^}]*\}\n?/s, "").replace(/\r\n/g, "\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED, await generate());
}
