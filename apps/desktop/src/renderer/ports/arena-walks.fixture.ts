function toPath(flat: readonly number[]): Path {
  const points: (readonly [number, number])[] = [];
  for (let index = 0; index + 1 < flat.length; index += 2) {
    points.push([flat[index] ?? 0, flat[index + 1] ?? 0]);
  }
  return points;
}

